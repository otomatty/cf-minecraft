/** Resolve the item registry's texture key, including art prepared for future mob drops. */
export function itemTexture(name: string): Uint8Array | undefined {
	const sprite = sprites.get(name);
	return sprite && pixelTile(sprite.rows, sprite.palette);
}

export function hasItemTexture(name: string): boolean {
	return sprites.has(name);
}
