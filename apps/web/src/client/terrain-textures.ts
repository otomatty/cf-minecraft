// A dot exposes the substrate at the same coordinates on both plain and mineral-bearing faces.
function overlay(base: Tile, detail: Tile): Tile {
	return {
		palette: { ...base.palette, ...detail.palette },
		rows: detail.rows.map((row, y) => Array.from(row, (c, x) => c === "." ? base.rows[y][x] : c).join("")),
	};
}

