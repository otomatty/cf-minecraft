const terrainTiles = new Map<string, Tile>([
	["stone", stone], ["dirt", dirt], ["coarse_dirt", coarseDirt], ["cobblestone", cobblestone],
	["bedrock", bedrock], ["gravel", gravel], ["sand", sand], ["snow_block", snow],
	["sandstone", sandstone], ["sandstone_top", sandstoneTop], ["sandstone_bottom", sandstoneBottom],
	["coal_ore", coal], ["copper_ore", copper], ["iron_ore", iron], ["gold_ore", gold],
]);

export function terrainTexture(name: string): Uint8Array | undefined {
	const tile = terrainTiles.get(name);
	return tile && pixelTile(tile.rows, tile.palette);
}
