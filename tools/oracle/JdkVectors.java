import java.util.Random;

/**
 * Prints reference values from the JDK itself (no game code involved).
 *
 * Run from the repository root:
 *   javac --add-modules jdk.random --add-exports jdk.random/jdk.random=ALL-UNNAMED -d /tmp/oracle tools/oracle/JdkVectors.java
 *   java  --add-modules jdk.random --add-exports jdk.random/jdk.random=ALL-UNNAMED -cp /tmp/oracle JdkVectors \
 *     > crates/jmath/tests/vectors/jdk.txt
 */
public class JdkVectors {
    static final long[] SEEDS = {0L, 1L, 42L, -1L, 123456789L, Long.MIN_VALUE, Long.MAX_VALUE, 0x5DEECE66DL, -4962768465676381896L};
    static final int[] BOUNDS = {1, 2, 3, 10, 16, 100, 1000, 1 << 16, (1 << 30) + 1, 1_000_000_007, Integer.MAX_VALUE};
    static final int N = 8;

    public static void main(String[] args) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by tools/oracle/JdkVectors.java on ").append(System.getProperty("java.version")).append('\n');
        for (long seed : SEEDS) {
            Random r = new Random(seed);
            sb.append("R ").append(seed).append(" nextInt");
            for (int i = 0; i < N; i++) sb.append(' ').append(r.nextInt());
            sb.append('\n');

            for (int bound : BOUNDS) {
                r = new Random(seed);
                sb.append("R ").append(seed).append(" nextIntBound ").append(bound);
                for (int i = 0; i < N; i++) sb.append(' ').append(r.nextInt(bound));
                sb.append('\n');
            }

            r = new Random(seed);
            sb.append("R ").append(seed).append(" nextLong");
            for (int i = 0; i < N; i++) sb.append(' ').append(r.nextLong());
            sb.append('\n');

            r = new Random(seed);
            sb.append("R ").append(seed).append(" nextFloatBits");
            for (int i = 0; i < N; i++) sb.append(' ').append(Float.floatToRawIntBits(r.nextFloat()));
            sb.append('\n');

            r = new Random(seed);
            sb.append("R ").append(seed).append(" nextDoubleBits");
            for (int i = 0; i < N; i++) sb.append(' ').append(Double.doubleToRawLongBits(r.nextDouble()));
            sb.append('\n');

            r = new Random(seed);
            sb.append("R ").append(seed).append(" nextBoolean");
            for (int i = 0; i < N * 2; i++) sb.append(' ').append(r.nextBoolean() ? 1 : 0);
            sb.append('\n');

            // Interleaved calls: checks that every method advances the state identically.
            r = new Random(seed);
            sb.append("R ").append(seed).append(" mixed");
            for (int i = 0; i < 4; i++) {
                sb.append(' ').append(r.nextInt());
                sb.append(' ').append(r.nextInt(100));
                sb.append(' ').append(r.nextLong());
                sb.append(' ').append(Double.doubleToRawLongBits(r.nextDouble()));
                sb.append(' ').append(Float.floatToRawIntBits(r.nextFloat()));
                sb.append(' ').append(r.nextBoolean() ? 1 : 0);
            }
            sb.append('\n');
        }

        long[][] states = {{1L, 2L}, {-1L, -1L}, {0x0123456789ABCDEFL, 0xFEDCBA9876543210L}, {Long.MIN_VALUE, 1L}, {42L, 0L}};
        for (long[] s : states) {
            jdk.random.Xoroshiro128PlusPlus x = new jdk.random.Xoroshiro128PlusPlus(s[0], s[1]);
            sb.append("X ").append(s[0]).append(' ').append(s[1]).append(" nextLong");
            for (int i = 0; i < N; i++) sb.append(' ').append(x.nextLong());
            sb.append('\n');
        }
        System.out.print(sb);
    }
}
